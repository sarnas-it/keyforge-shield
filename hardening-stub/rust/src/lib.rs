// вместо явного отказа при обнаружении подмены. В прототипе — no-op заглушка.

/// Проба "жив ли hardening-слой и совместим ли с текущим ABI core".
/// Возвращает 1 — слой присутствует и готов. В реальной реализации сюда
/// добавятся побочные эффекты: обновление таймингового окна, инкремент
/// счётчика вызовов для детекции аномальной частоты обращений и т.п.
#[no_mangle]
pub extern "C" fn hardening_probe() -> i32 {
    1
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn probe_reports_present() {
        assert_eq!(hardening_probe(), 1);
    }
}
