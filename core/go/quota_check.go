package keyforgeshield

// Эти константы зеркалят строки, которые serde кладёт в SeatMode.Mode
// (core/rust/src/token.rs, #[serde(tag = "mode", rename_all = "snake_case")]).
const (
	SeatModeNamedUsers   = "named_users"
	SeatModeDeviceLocked = "device_locked"
	SeatModeUnbound      = "unbound"
)

// CheckSeatCount и CheckUsageQuota — чистые функции сравнения, без
// собственного хранения состояния. keyforge-shield не владеет и не
// хранит "сколько сейчас активно" / "сколько уже потрачено" — это
// репортит сам продукт из своего УЖЕ существующего надёжного учёта
// (таблица активных сессий, лог обработанных операций и т.п.), который
// ему всё равно нужен для собственной работы. Разделение ролей:
// продукт отвечает за надёжное хранение счётчика, SDK — только за
// решение "укладывается ли репортнутое значение в подписанный лимит".
//
// Раньше (до этого разделения) в SDK был отдельный файловый UsageCounter,
// которым владел сам SDK — он создавал слабое место: файл, который мы
// контролируем, проще потерять/стереть (переустановка, клонирование
// VM, поддержка "у меня файл лицензии повредился, пересоздайте"), чем
// собственную продуктовую БД, которая продукту и так нужна корректной
// для работы. Текущая схема переносит хранение туда, где оно и так
// обязано быть надёжным.
//
// ВАЖНО, что это НЕ меняет: репортнутое значение — самоотчёт клиентского
// кода. Скомпрометированный/патченный бинарь всё ещё технически может
// соврать про текущее значение — это тот же класс ограничения, что и у
// любой другой офлайн-проверки в этом протоколе (справедливость, не
// неуязвимость — см. обсуждение бизнес-модели). Разница не в защите от
// целенаправленной атаки, а в том, что честный, но неаккуратный клиент
// не теряет корректность учёта случайно.

// CheckSeatCount сообщает, укладывается ли reportedActive (текущее
// количество активных пользователей/сессий, которое продукт репортит из
// своего собственного учёта) в лимит mode. DeviceLocked/Unbound не
// ограничивают по счётчику — true всегда (их проверка другая: привязка
// к устройству проверяется иначе, не через этот счётчик).
func CheckSeatCount(reportedActive uint32, mode SeatMode) bool {
	if mode.Mode != SeatModeNamedUsers {
		return true
	}
	return reportedActive <= mode.Count
}

// CheckUsageQuota сообщает, укладывается ли reportedUsage (значение,
// которое продукт репортит из своего собственного учёта потребления) в
// лимит quota. quota == nil означает "в токене нет квоты на эту ось" —
// всегда true. reportedUsage == quota.Limit считается ИСЧЕРПАННЫМ
// (лимит "не более N", N-е использование уже укладывается, N+1-е не
// должно пройти — вызывающая сторона должна проверить ДО выполнения
// операции, передав текущее количество уже выполненных).
func CheckUsageQuota(reportedUsage uint64, quota *UsageInfo) bool {
	if quota == nil {
		return true
	}
	return reportedUsage < quota.Limit
}
